import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = new URL('../', import.meta.url);
export function outputs() {
  const sql = JSON.parse(readFileSync(new URL('shared/apme-read-indexes.json', root), 'utf8'));
  if (!Array.isArray(sql) || !sql.length || sql.some(value => typeof value !== 'string' || !/^CREATE INDEX IF NOT EXISTS idx_/.test(value))) {
    throw new Error('Invalid APME read indexes');
  }
  const header = '// Generated by scripts/generate-apme-read-indexes.mjs; edit shared/apme-read-indexes.json.\n';
  const files = [
    ['bridge/src/apme/read-indexes.generated.ts', header + 'export const APME_HOT_READ_INDEXES = ' + JSON.stringify(sql, null, 2) + ' as const;\n'],
    ['apple/AgentDeck/Daemon/Apme/ApmeReadIndexes.generated.swift', header + '#if os(macOS)\nenum ApmeReadIndexes {\n    static let sql = [\n' + sql.map(value => `        #"${value}"#,`).join('\n') + '\n    ]\n}\n#endif\n'],
  ];
  return files.map(([relative, expected]) => {
    const path = fileURLToPath(new URL(relative, root));
    return { path, expected, current: existsSync(path) ? readFileSync(path, 'utf8') : null };
  });
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { path, current, expected } of outputs()) {
    if (process.argv.includes('--check')) {
      if (current !== expected) throw new Error(`APME read index drift: ${path}`);
    } else if (current !== expected) writeFileSync(path, expected);
  }
}
